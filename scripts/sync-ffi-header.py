#!/usr/bin/env python3
"""Generate both C headers from the public Rust ABI; fail closed on unknown types."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/desklink-ffi/src/lib.rs"
HEADERS = [ROOT / "crates/desklink-ffi/include/desklink.h", ROOT / "apps/apple/Sources/DeskLinkC/include/desklink.h"]
PREFIX = {"DesklinkPlatform": "PLATFORM_", "DesklinkResult": "", "DesklinkState": "", "DesklinkEventKind": "EVENT_", "DesklinkInputKind": "INPUT_", "DesklinkHostEventKind": "HOST_EVENT_", "DesklinkHostState": "HOST_", "DesklinkControllerCommand": "COMMAND_"}
SCALARS = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t", "i32": "int32_t", "f32": "float", "usize": "size_t", "c_char": "char", "c_void": "void"}


def snake(name):
    if name in {"MacOS", "IOS", "H264AccessUnit", "InvalidUtf8"}:
        return {"MacOS": "MACOS", "IOS": "IOS", "H264AccessUnit": "H264_ACCESS_UNIT", "InvalidUtf8": "INVALID_UTF8"}[name]
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def ctype(kind):
    kind = kind.strip()
    if kind.startswith("*const "):
        return "const " + ctype(kind[7:]) + " *"
    if kind.startswith("*mut "):
        return ctype(kind[5:]) + " *"
    if re.fullmatch(r"Option<Desklink\w+Callback>", kind):
        return kind[7:-1]
    if kind in SCALARS:
        return SCALARS[kind]
    if re.fullmatch(r"Desklink\w+", kind):
        return kind
    raise ValueError(f"Unsupported ABI type: {kind}")


def declaration(name, kind):
    array = re.fullmatch(r"\[(\w+); ([^]]+)\]", kind)
    if array:
        length = array[2].replace("PAIRING_CODE_BYTES + 1", "9")
        if not length.isdecimal():
            raise ValueError(f"Unsupported array length: {length}")
        return f"{ctype(array[1])} {name}[{length}]"
    return f"{ctype(kind)} {name}"


def generate(source):
    chunks = ['#ifndef DESKLINK_H\n#define DESKLINK_H', '/* Generated by scripts/sync-ffi-header.py from Rust. Do not edit. */', '#include <stddef.h>\n#include <stdint.h>', '#define DESKLINK_PAIRING_INVITE_BYTES 181\n#define DESKLINK_DIRECTORY_ACCESS_CODE_BYTES 8', '#ifdef __cplusplus\nextern "C" {\n#endif', 'typedef struct DesklinkHandle DesklinkHandle;\ntypedef struct DesklinkHostHandle DesklinkHostHandle;']
    for name, body in re.findall(r"pub enum (Desklink\w+) \{([^}]+)\}", source):
        prefix = PREFIX[name]  # An added enum requires an explicit C naming policy.
        values = re.findall(r"(\w+) = (\d+)", body)
        chunks.append(f"typedef enum {name} {{\n" + ''.join(f"    DESKLINK_{prefix}{snake(key)} = {value},\n" for key, value in values) + f"}} {name};")
    # Key constants are extracted from the production Rust conversion.
    keys = [("CHARACTER", 0)] + [(snake(key), int(value)) for key, value in re.findall(r"KeyCode::(\w+) => \((\d+), 0\)", source)] + [(f"F{n}", 15 + n) for n in range(1, 13)]
    chunks.append('typedef enum DesklinkKeyCode {\n' + ''.join(f'    DESKLINK_KEY_{key} = {value},\n' for key, value in sorted(keys, key=lambda item: item[1])) + '} DesklinkKeyCode;')
    chunks.append('typedef enum DesklinkModifier {\n    DESKLINK_MODIFIER_SHIFT = 1,\n    DESKLINK_MODIFIER_CONTROL = 2,\n    DESKLINK_MODIFIER_ALT = 4,\n    DESKLINK_MODIFIER_META = 8,\n} DesklinkModifier;')
    for name, body in re.findall(r"#\[repr\(C\)\]\s*(?:#\[[^\n]+\]\s*)*pub struct (Desklink\w+) \{([^}]+)\}", source):
        fields = re.findall(r"pub (\w+): ([^,]+),", body)
        chunks.append(f'typedef struct {name} {{\n' + ''.join(f'    {declaration(field, kind)};\n' for field, kind in fields) + f'}} {name};')
    chunks.append('/* Event bytes are borrowed only for the callback duration.\n * Error: error_code 1 reconnecting, 2 video recovery, 3 terminal; recoverable is explicit.\n * Capabilities payload v1: [version, platform(1 Windows/2 Mac/3 iOS), width:u16le, height:u16le, H264 profile bitmask(Main=1,High=2)].\n * Each handle requires exclusive caller access; destroy joins the worker and ends callbacks. */\ntypedef void (*DesklinkEventCallback)(void *, const DesklinkEvent *);\ntypedef void (*DesklinkHostEventCallback)(void *, const DesklinkHostEvent *);')
    functions = re.findall(r'pub (?:unsafe )?extern "C" fn (desklink_\w+)\((.*?)\)\s*(?:-> (\w+)\s*)?\{', source, re.S)
    for name, params, result in functions:
        args = []
        for param in params.split(','):
            if param.strip():
                arg, kind = param.strip().split(':', 1)
                args.append(declaration(arg, kind.strip()))
        chunks.append(f'{ctype(result) if result else "void"} {name}(' + ', '.join(args or ['void']) + ');')
    chunks.append('#ifdef __cplusplus\n}\n#endif\n\n#endif\n')
    return '\n\n'.join(chunks)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(SOURCE.read_text(encoding='utf-8')).encode('utf-8')
    for header in HEADERS:
        if args.check:
            if header.read_bytes() != generated:
                raise SystemExit(f'ABI header drift: {header.relative_to(ROOT)}; run python scripts/sync-ffi-header.py')
        else:
            header.write_bytes(generated)
    print('Both ABI headers match public Rust enums, structs and exported signatures.')


if __name__ == '__main__':
    main()
